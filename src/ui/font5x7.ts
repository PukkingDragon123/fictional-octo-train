const BITS = new Map<string, Uint8Array>();
for (const [ch, s] of Object.entries(G)) {
  const rows = s.split(' ');
  const b = new Uint8Array(35);
  rows.forEach((r, y) => { for (let x = 0; x < 5; x++) b[y * 5 + x] = r[x] === '#' ? 1 : 0; });
  BITS.set(ch, b);
}
const FALLBACK = BITS.get('?')!;

/** RGBA pixel buffer the scanner draws into */
export class Screen {
  w: number; h: number;
  data: Uint32Array;
  img: ImageData;
  constructor(w: number, h: number) {
    this.w = w; this.h = h;
    this.img = new ImageData(w, h);
    this.data = new Uint32Array(this.img.data.buffer);
  }
  /** colour as 0xRRGGBB -> little endian ABGR */
  static c(rgb: number, a = 255) { return ((a << 24) | ((rgb & 0xff) << 16) | (rgb & 0xff00) | ((rgb >> 16) & 0xff)) >>> 0; }
  clear(rgb: number) { this.data.fill(Screen.c(rgb)); }
  px(x: number, y: number, c: number) { x |= 0; y |= 0; if (x < 0 || y < 0 || x >= this.w || y >= this.h) return; this.data[y * this.w + x] = c; }
  rect(x: number, y: number, w: number, h: number, c: number) { for (let j = 0; j < h; j++) for (let i = 0; i < w; i++) this.px(x + i, y + j, c); }
  frame(x: number, y: number, w: number, h: number, c: number) { for (let i = 0; i < w; i++) { this.px(x + i, y, c); this.px(x + i, y + h - 1, c); } for (let j = 0; j < h; j++) { this.px(x, y + j, c); this.px(x + w - 1, y + j, c); } }
  hline(x0: number, x1: number, y: number, c: number, dash = 0) { for (let x = x0; x <= x1; x++) if (!dash || ((x - x0) % dash) < dash / 2) this.px(x, y, c); }
  vline(x: number, y0: number, y1: number, c: number) { for (let y = y0; y <= y1; y++) this.px(x, y, c); }
  line(x0: number, y0: number, x1: number, y1: number, c: number) {
    x0 = Math.round(x0); y0 = Math.round(y0); x1 = Math.round(x1); y1 = Math.round(y1);
    const dx = Math.abs(x1 - x0), dy = -Math.abs(y1 - y0), sx = x0 < x1 ? 1 : -1, sy = y0 < y1 ? 1 : -1;
    let err = dx + dy;
    for (let g = 0; g < 2000; g++) { this.px(x0, y0, c); if (x0 === x1 && y0 === y1) break; const e2 = 2 * err; if (e2 >= dy) { err += dy; x0 += sx; } if (e2 <= dx) { err += dx; y0 += sy; } }
  }
  circle(cx: number, cy: number, r: number, c: number, dash = 0) {
    const n = Math.max(12, Math.floor(r * 6));
    for (let i = 0; i < n; i++) { if (dash && i % dash >= dash / 2) continue; const a = (i / n) * Math.PI * 2; this.px(cx + Math.cos(a) * r, cy + Math.sin(a) * r, c); }
  }
  disc(cx: number, cy: number, r: number, c: number) { for (let y = -r; y <= r; y++) for (let x = -r; x <= r; x++) if (x * x + y * y <= r * r) this.px(cx + x, cy + y, c); }
  /** draw text; returns width in pixels. scale 1 = 5x7 glyphs with 1px spacing */
  text(s: string, x: number, y: number, c: number, scale = 1, maxW = 9999): number {
    let cx = x;
    for (const ch of s) {
      if (cx - x + 6 * scale > maxW) { this.text('…', cx, y, c, scale); break; }
      const b = BITS.get(ch) || BITS.get(ch.toUpperCase()) || FALLBACK;
      for (let j = 0; j < 7; j++) for (let i = 0; i < 5; i++) if (b[j * 5 + i]) {
        if (scale === 1) this.px(cx + i, y + j, c); else this.rect(cx + i * scale, y + j * scale, scale, scale, c);
      }
      cx += 6 * scale;
    }
    return cx - x;
  }
  textW(s: string, scale = 1) { return [...s].length * 6 * scale; }
  /** word-wrapped text block; returns lines used */
  para(s: string, x: number, y: number, w: number, c: number, lineH = 9, maxLines = 99): number {
    const words = s.split(/\s+/);
    let line = '', n = 0;
    const flush = () => { if (n < maxLines) this.text(line, x, y + n * lineH, c); n++; line = ''; };
    for (const wd of words) {
      if (wd === '\\n') { flush(); continue; }
      const test = line ? line + ' ' + wd : wd;
      if (this.textW(test) > w && line) { flush(); line = wd; } else line = test;
    }
    if (line) flush();
    return n;
  }
  bar(x: number, y: number, w: number, h: number, v: number, fg: number, bg: number) {
    this.frame(x, y, w, h, fg);
    this.rect(x + 1, y + 1, w - 2, h - 2, bg);
    const f = Math.round((w - 2) * Math.max(0, Math.min(1, v)));
    for (let i = 0; i < f; i++) for (let j = 1; j < h - 1; j++) if ((i & 1) === 0 || h < 5) this.px(x + 1 + i, y + j, fg);
  }
}
