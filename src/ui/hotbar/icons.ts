export type CtxIcon = keyof typeof CTX_ART;

const cache = new Map<string, string>();
/** the icon as a data URL (18x18: the art, its outline and a 1px shadow) */
export function ctxIconUrl(name: string): string {
  const hit = cache.get(name);
  if (hit) return hit;
  const rows = CTX_ART[name] || CTX_ART.letgo;
  const W = 18, H = 18;
  const grid: string[][] = [];
  for (let y = 0; y < 16; y++) grid.push((rows[y] || '').padEnd(16, '.').slice(0, 16).split(''));
  const filled = (x: number, y: number) => x >= 0 && y >= 0 && x < 16 && y < 16 && grid[y][x] !== '.';
  const c = document.createElement('canvas'); c.width = W; c.height = H;
  const x2 = c.getContext('2d')!;
  const img = x2.createImageData(W, H);
  const put = (x: number, y: number, col: number, a = 255) => {
    if (x < 0 || y < 0 || x >= W || y >= H) return;
    const i = (y * W + x) * 4;
    if (img.data[i + 3] && a < 255) return;
    img.data[i] = (col >> 16) & 255; img.data[i + 1] = (col >> 8) & 255; img.data[i + 2] = col & 255; img.data[i + 3] = a;
  };
  // the art at (1, 1), outlined, then a shadow one pixel down-right of the outline
  const ol = (x: number, y: number) => !filled(x, y) && (filled(x + 1, y) || filled(x - 1, y) || filled(x, y + 1) || filled(x, y - 1));
  for (let y = 0; y < 16; y++) for (let x = 0; x < 16; x++) if (filled(x, y)) put(x + 1, y + 1, PAL[grid[y][x]] ?? 0xff00ff);
  for (let y = -1; y <= 16; y++) for (let x = -1; x <= 16; x++) if (ol(x, y)) put(x + 1, y + 1, PAL.k);
  for (let y = -1; y <= 16; y++) for (let x = -1; x <= 16; x++) if (filled(x, y) || ol(x, y)) put(x + 2, y + 2, 0x000000, 110);
  x2.putImageData(img, 0, 0);
  const url = c.toDataURL();
  cache.set(name, url);
  return url;
}
